/* Service worker: lets the shop app open with no signal. Version changes whenever the owner saves. */
const VERSION = "5e6ab55ad2";
const LOGO = "";
const CACHE = "shop-" + VERSION;
const SHELL = ["./", "index.html", "app.js", "style.css", "manifest.webmanifest", "content.json",
               "icons/icon-192.png", "icons/icon-512.png"].concat(LOGO ? [LOGO] : []);
self.addEventListener("install", e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting())); });
self.addEventListener("activate", e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith("shop-") && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("fetch", e => {
  const u = new URL(e.request.url);
  if (e.request.method !== "GET" || u.origin !== location.origin) return;
  if (u.pathname.endsWith("content.json")) {          // fresh prices when online, saved copy when offline
    e.respondWith(fetch(e.request).then(r => { const c = r.clone(); caches.open(CACHE).then(x => x.put(e.request, c)); return r; })
      .catch(() => caches.match(e.request)));
    return;
  }
  e.respondWith(caches.match(e.request).then(hit => hit || fetch(e.request).then(r => {
    if (r.ok) { const c = r.clone(); caches.open(CACHE).then(x => x.put(e.request, c)); } return r; })
    .catch(() => caches.match("index.html"))));
});
